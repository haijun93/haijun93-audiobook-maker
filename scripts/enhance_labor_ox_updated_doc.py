def parse_docx(path: Path) -> list[QuestionBlock]:
    doc = Document(str(path))
    section = ""
    items: list[QuestionBlock] = []
    current: dict[str, str | int] | None = None
    in_body = False
    for para in doc.paragraphs:
        text = para.text.strip()
        if not text:
            continue
        if not in_body:
            if "OX 본문" in text:
                in_body = True
            continue
        if text.startswith("■ "):
            section = text[2:].strip()
            continue
        if text in SECTION_ORDER:
            section = text
            continue
        if text.startswith("최근 3년 출제량:"):
            continue
        match = re.match(r"^(\d+)\.\s*(.*)$", text)
        if match:
            if current:
                items.append(
                    QuestionBlock(
                        original_no=int(current["original_no"]),
                        number=int(current["original_no"]),
                        section=str(current["section"]),
                        statement=str(current["statement"]),
                        answer=str(current.get("answer", "")).strip(),
                        basis=str(current.get("basis", "")).strip(),
                        explanation=str(current.get("explanation", "")).strip(),
                        source=str(current.get("source", "")).strip(),
                    )
                )
            current = {
                "original_no": int(match.group(1)),
                "section": section,
                "statement": match.group(2).strip(),
            }
            continue
        if not current:
            continue
        if text.startswith("● 정답:") or text.startswith("정답:"):
            current["answer"] = text.split(":", 1)[1].strip()
        elif text.startswith("근거:"):
            current["basis"] = text.split(":", 1)[1].strip()
        elif text.startswith("해설:"):
            current["explanation"] = text.split(":", 1)[1].strip()
        elif text.startswith("출처:"):
            current["source"] = text.split(":", 1)[1].strip()

    if current:
        items.append(
            QuestionBlock(
                original_no=int(current["original_no"]),
                number=int(current["original_no"]),
                section=str(current["section"]),
                statement=str(current["statement"]),
                answer=str(current.get("answer", "")).strip(),
                basis=str(current.get("basis", "")).strip(),
                explanation=str(current.get("explanation", "")).strip(),
                source=str(current.get("source", "")).strip(),
            )
        )
    return items


