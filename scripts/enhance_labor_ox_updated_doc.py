def compute_recent_trend(entries: list[dict[str, object]]) -> dict[str, object]:
    recent = [entry for entry in entries if str(entry["year"]) in {"2023", "2024", "2025"}]
    topic_year_counts: dict[str, dict[str, int]] = {topic: {"2023": 0, "2024": 0, "2025": 0} for topic in SECTION_ORDER}
    for entry in recent:
        topic = str(entry["topic"])
        year = str(entry["year"])
        if topic in topic_year_counts:
            topic_year_counts[topic][year] += 1

    trap_patterns = {
        "주체·권한형": re.compile(r"(장관|위원회|사용자|근로자|노동조합|지방노동위원회|중앙노동위원회|공익위원|근로자위원|사용자위원)"),
        "기간·수치형": re.compile(r"(\d+일|\d+개월|\d+년|과반수|3분의 2|100분의|이상|이내|초과)"),
        "부정문형": re.compile(r"(아니한다|없다|할 수 없다|제외된다|못한다)"),
        "판례형": re.compile(r"(판례|다툼이 있으면 판례|대법원|헌법재판소)"),
        "위원회·절차형": re.compile(r"(위원회|심판|재심|구제신청|의결|출석|회의|심의)"),
    }
    trap_counts = {}
    for year in ("2023", "2024", "2025"):
        items = [entry for entry in recent if str(entry["year"]) == year]
        trap_counts[year] = {
            label: sum(1 for entry in items if pattern.search(str(entry["statement"])))
            for label, pattern in trap_patterns.items()
        }
    committee_count = {
        year: sum(
            1
            for entry in recent
            if str(entry["year"]) == year
            and re.search(
                r"(위원회|노동위원회|최저임금위원회|노사협의회|고충처리위원|산업안전보건위원회|근로시간면제심의위원회)",
                str(entry["statement"]),
            )
        )
        for year in ("2023", "2024", "2025")
    }
    return {
        "topic_year_counts": topic_year_counts,
        "trap_counts": trap_counts,
        "committee_count": committee_count,
    }


def classify_trap(statement: str) -> str:
    text = normalize_text(statement)
    if re.search(r"(위원회|심판|재심|구제신청|의결|출석|회의|심의)", text):
        return "위원회·절차형"
    if re.search(r"(\d+일|\d+개월|\d+년|과반수|3분의 2|100분의|이상|이내|초과)", text):
        return "기간·수치형"
    if re.search(r"(장관|사용자|근로자|노동조합|공익위원|근로자위원|사용자위원)", text):
        return "주체·권한형"
    if re.search(r"(판례|다툼이 있으면 판례|대법원|헌법재판소)", text):
        return "판례형"
    if re.search(r"(아니한다|없다|할 수 없다|제외된다|못한다)", text):
        return "부정문형"
    return "문언형"


