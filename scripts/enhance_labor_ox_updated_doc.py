def backup_file(path: Path) -> Path:
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    backup = path.with_name(f"{path.stem}_backup_before_enhance_{timestamp}{path.suffix}")
    backup.write_bytes(path.read_bytes())
    return backup


def main() -> None:
    parser = argparse.ArgumentParser(description="노동법 OX updated 문서를 2026 대비형으로 보강합니다.")
    parser.add_argument("input_file", nargs="?", type=Path, default=DEFAULT_INPUT)
    args = parser.parse_args()

    input_file: Path = args.input_file
    if not input_file.exists():
        raise SystemExit(f"입력 파일을 찾을 수 없습니다: {input_file}")

    backup = backup_file(input_file)
    items = parse_docx(input_file)
    prepared, removed_low_quality = prepare_questions(items)
    trend = compute_recent_trend(load_recent_trend_entries(SOURCE_JSON))
    build_document(prepared, trend, input_file, removed_low_quality)
    print(f"backup={backup}")
    print(f"updated={input_file}")
    print(f"removed_low_quality={removed_low_quality}")
    print(f"final_questions={len(prepared)}")


if __name__ == "__main__":
    main()
