@dataclass
class QuestionBlock:
    original_no: int
    number: int
    section: str
    statement: str
    answer: str
    basis: str
    explanation: str
    source: str


def normalize_text(text: str) -> str:
    text = text.replace("\u00a0", " ").replace("\u200b", "")
    text = text.replace("•", "·").replace("ㆍ", "·")
    text = text.replace("“", '"').replace("”", '"').replace("’", "'").replace("‘", "'")
    text = re.sub(r"\s+", " ", text)
    return text.strip()


def compact_text(text: str) -> str:
    return re.sub(r"[^0-9A-Za-z가-힣]", "", normalize_text(text))


def needs_spacing(text: str) -> bool:
    compact = re.sub(r"[^가-힣]", "", text)
    if len(compact) >= 12 and " " not in text:
        return True
    if re.search(r"[가-힣]{8,}", text):
        return True
    return False


KIWI = Kiwi()


def apply_legal_replacements(text: str) -> str:
    updated = text
    for before, after in LEGAL_REPLACEMENTS.items():
        updated = updated.replace(before, after)
    for pattern, replacement in LEGAL_REGEX_REPLACEMENTS:
        updated = re.sub(pattern, replacement, updated)
    updated = re.sub(
        r"(하여야|되어야|보아야|두어야|받아야|있어야|없어야|않아야|해서는)(?=(한다|된다|할|될))",
        r"\1 ",
        updated,
    )
    updated = re.sub(r"\s*·\s*", "·", updated)
    updated = re.sub(r"\b일\s*·\s*가정\b", "일·가정", updated)
    updated = re.sub(r"\b정답은\s*([OX])입니다\.", r"정답은 \1입니다.", updated)
    updated = re.sub(r"\s+([.,;:])", r"\1", updated)
    updated = re.sub(r"\(\s+", "(", updated)
    updated = re.sub(r"\s+\)", ")", updated)
    updated = re.sub(r"\s{2,}", " ", updated)
    return updated.strip()


def has_sentence_predicate(statement: str) -> bool:
    return bool(
        re.search(
            r"(다|한다|된다|있다|없다|받는다|진다|필요하다|해당한다|불가능하다|가능하다|해야 한다|할 수 있다|할 수 없다)\.?$",
            normalize_text(statement),
        )
    )


def is_context_free_fragment(statement: str) -> bool:
    normalized = normalize_text(statement)
    compact = compact_text(normalized)
    if not normalized:
        return False
    if re.fullmatch(r"[0-9,]+(개|명|원|만원|일|개월|년)", compact):
        return True
    if re.fullmatch(r"[ㄱ-ㅎ0-9A-Za-z:]+", compact) and len(compact) <= 30:
        return True
    if normalized.startswith("ㄱ") or normalized.startswith("①") or normalized.startswith("7:"):
        return True
    if ("만 필요하다" in normalized or "모두 필요하다" in normalized) and len(compact) <= 25:
        return True
    if not has_sentence_predicate(normalized) and len(compact) <= 45:
        return True
    return False


def space_legal_text(text: str) -> str:
    normalized = normalize_text(text)
    if not normalized:
        return normalized
    if needs_spacing(normalized):
        normalized = KIWI.space(normalized)
    return apply_legal_replacements(normalized)


def strip_useless_explanation(text: str) -> str:
    updated = normalize_text(text)
    for pattern in USELESS_EXPLANATION_PATTERNS:
        updated = re.sub(pattern, "", updated)
    updated = re.sub(r"\s{2,}", " ", updated)
    return updated.strip(" .")


