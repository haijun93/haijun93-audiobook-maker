def apply_text_replacements(name: str, text: str, counts: Counter[str]) -> str:
    for old, new in GLOBAL_REPLACEMENTS:
        n = text.count(old)
        if n:
            text = text.replace(old, new)
            counts[f"global:{old}"] += n

    for pattern, new in REGEX_REPLACEMENTS:
        text, n = pattern.subn(new, text)
        if n:
            counts[f"regex:{pattern.pattern}"] += n

    for old, new in CHAPTER_REPLACEMENTS.get(name, []):
        n = text.count(old)
        if n:
            text = text.replace(old, new)
            counts[f"{name}:{old[:24]}"] += n
    return text


def apply_ko_span_replacements(name: str, text: str, counts: Counter[str]) -> str:
    """Apply fixes only inside bilingual EPUB Korean spans, preserving English text."""

    def replace_match(match: re.Match[str]) -> str:
        prefix, content, suffix = match.groups()
        new_content = apply_text_replacements(name, content, counts)
        return f"{prefix}{new_content}{suffix}"

    return re.sub(r'(<span\b[^>]*class="ko"[^>]*>)(.*?)(</span>)', replace_match, text, flags=re.DOTALL)


def rewrite_epub(epub_path: Path, dry_run: bool = False, ko_spans_only: bool = False) -> tuple[Path | None, Counter[str]]:
    if not epub_path.exists():
        raise FileNotFoundError(epub_path)

    counts: Counter[str] = Counter()
    backup_path: Path | None = None

    with tempfile.TemporaryDirectory() as tmp_name:
        tmp_path = Path(tmp_name)
        out_path = tmp_path / epub_path.name

        with zipfile.ZipFile(epub_path, "r") as zin, zipfile.ZipFile(out_path, "w") as zout:
            infos = zin.infolist()
            mimetype_info = next((info for info in infos if info.filename == "mimetype"), None)
            ordered_infos = []
            if mimetype_info is not None:
                ordered_infos.append(mimetype_info)
            ordered_infos.extend(info for info in infos if info.filename != "mimetype")

            for info in ordered_infos:
                data = zin.read(info.filename)
                suffix = Path(info.filename).suffix.lower()
                if suffix in TEXT_SUFFIXES:
                    try:
                        text = data.decode("utf-8")
                    except UnicodeDecodeError:
                        pass
                    else:
                        if ko_spans_only:
                            if suffix in HTML_SUFFIXES:
                                text = apply_ko_span_replacements(info.filename, text, counts)
                                data = text.encode("utf-8")
                        else:
                            new_text = apply_text_replacements(info.filename, text, counts)
                            data = new_text.encode("utf-8")

                zip_info = zipfile.ZipInfo(info.filename, date_time=info.date_time)
                zip_info.comment = info.comment
                zip_info.extra = info.extra
                zip_info.internal_attr = info.internal_attr
                zip_info.external_attr = info.external_attr
                zip_info.create_system = info.create_system
                zip_info.compress_type = zipfile.ZIP_STORED if info.filename == "mimetype" else zipfile.ZIP_DEFLATED
                zout.writestr(zip_info, data)

        validate_epub(out_path)

        if dry_run:
            return None, counts

        BACKUP_DIR.mkdir(parents=True, exist_ok=True)
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        backup_path = BACKUP_DIR / f"{epub_path.stem}.before_dark_notes_tone_{timestamp}{epub_path.suffix}"
        shutil.copy2(epub_path, backup_path)
        shutil.move(str(out_path), epub_path)

    return backup_path, counts


def validate_epub(epub_path: Path) -> None:
    with zipfile.ZipFile(epub_path, "r") as zf:
        names = zf.namelist()
        if not names or names[0] != "mimetype":
            raise ValueError("EPUB mimetype entry is not first")
        if zf.read("mimetype") != b"application/epub+zip":
            raise ValueError("EPUB mimetype content is invalid")
        for info in zf.infolist():
            suffix = Path(info.filename).suffix.lower()
            if suffix not in {".xhtml", ".xml", ".opf", ".ncx"}:
                continue
            safe_fromstring(zf.read(info.filename))


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--epub", type=Path, default=DEFAULT_EPUB)
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument(
        "--ko-spans-only",
        action="store_true",
        help="Only rewrite Korean spans in bilingual [k-e] EPUBs, leaving English originals intact.",
    )
    args = parser.parse_args()

    backup_path, counts = rewrite_epub(args.epub, dry_run=args.dry_run, ko_spans_only=args.ko_spans_only)
    print(f"epub={args.epub}")
    if backup_path:
        print(f"backup={backup_path}")
    print(f"changed_items={len(counts)}")
    print(f"total_replacements={sum(counts.values())}")
    for key, value in counts.most_common():
        print(f"{value:4d}  {key}")


if __name__ == "__main__":
    main()
