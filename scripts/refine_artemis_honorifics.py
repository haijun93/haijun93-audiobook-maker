def write_epub_with_replacements(input_path: Path, output_path: Path) -> dict[str, int]:
    counts: dict[str, int] = {}
    with zipfile.ZipFile(input_path, "r") as zin, zipfile.ZipFile(output_path, "w") as zout:
        names = zin.namelist()
        if "mimetype" in names:
            info = zipfile.ZipInfo("mimetype")
            info.compress_type = zipfile.ZIP_STORED
            zout.writestr(info, zin.read("mimetype"))

        for name in names:
            if name == "mimetype":
                continue

            data = zin.read(name)
            if name in REPLACEMENTS:
                text = data.decode("utf-8")
                for old, new in REPLACEMENTS[name]:
                    count = text.count(old)
                    if count:
                        text = text.replace(old, new)
                    counts[f"{name}: {old[:45]}"] = count
                data = text.encode("utf-8")

            original = zin.getinfo(name)
            info = zipfile.ZipInfo(name)
            info.date_time = original.date_time
            info.compress_type = original.compress_type if name == "mimetype" else zipfile.ZIP_DEFLATED
            info.external_attr = original.external_attr
            zout.writestr(info, data)
    return counts


def main() -> int:
    if not KE_EPUB.exists():
        raise SystemExit(f"Missing source EPUB: {KE_EPUB}")

    BACKUP.parent.mkdir(parents=True, exist_ok=True)
    if not BACKUP.exists():
        shutil.copy2(KE_EPUB, BACKUP)

    with tempfile.NamedTemporaryFile(suffix=".epub", delete=False) as tmp:
        tmp_path = Path(tmp.name)

    counts = write_epub_with_replacements(KE_EPUB, tmp_path)
    shutil.move(tmp_path, KE_EPUB)
    convert_epub(KE_EPUB, K_EPUB, overwrite=True)

    total = sum(counts.values())
    missed = [(k, v) for k, v in counts.items() if v == 0]
    print(f"Applied replacements: {total}")
    print(f"Missed replacements: {len(missed)}")
    for key, _ in missed[:30]:
        print(f"MISS {key}")
    if len(missed) > 30:
        print(f"... {len(missed) - 30} more")
    return 0 if total else 1


if __name__ == "__main__":
    sys.exit(main())
